test('карта: совпавшие координаты, клавиатура и честная ошибка подложки', async ({ page }) => {
  await page.route('https://tile.openstreetmap.org/**', route => route.abort());
  await page.goto('/map');
  const markers = page.locator('.pm-marker');
  await expect(markers.first()).toBeVisible();
  const data = await state(page);
  const known = data.events.filter(event => event.latitude !== null && event.longitude !== null);
  expect(await markers.count()).toBe(new Set(known.map(event => `${event.latitude},${event.longitude}`)).size);
  await expect(page.getByText(/Фон карты недоступен/)).toBeVisible();
  await markers.first().focus();
  await expect(markers.first()).toBeFocused();
  await page.keyboard.press('Enter');
  const popup = page.getByRole('dialog', { name: 'События в этой точке', exact: true });
  await expect(popup).toBeVisible();
  const choices = popup.locator('.pm-popup-event');
  expect(await choices.count()).toBeGreaterThan(1);
  const choice = choices.last();
  const id = await choice.getAttribute('data-event-id');
  const event = data.events.find(event => event.id === id)!;
  await choice.focus();
  await expect(page.locator('.pr-map-aside h2')).toHaveText(event.title);
  await page.keyboard.press('Enter');
  await expect(popup).toBeHidden();
  await expect(page.locator('.pm-marker[aria-pressed="true"]')).toBeFocused();
  await page.locator('.pr-map-aside').getByRole('link', { name: 'Читать новость' }).click();
  await expect(page).toHaveURL(new RegExp(`/news/${id}$`));
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(event.title);
});

test('ошибка запроса не рисует успех; быстрые клики не дублируют оценку', async ({ page }) => {
  await register(page);
  await page.goto('/notifications');
  const card = page.locator('[data-notification-event-id]').first();
  await expect(card).toBeVisible();
  let count = 0;
  let release: (() => void) | undefined;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/product/feedback/*', async route => {
    count += 1;
    await gate;
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Пробный отказ сохранения' } }) });
  });
  const button = card.getByRole('button', { name: /^Полезно:/ });
  await button.evaluate((element: HTMLButtonElement) => { element.click(); element.click(); });
  await expect(button).toBeDisabled();
  release!();
  await expect(page.getByRole('alert').filter({ hasText: 'Пробный отказ сохранения' })).toBeVisible();
  expect(count).toBe(1);
  await expect(button).toHaveAttribute('aria-pressed', 'false');
  await expect(button).toBeDisabled();
  expect((await state(page)).events.every(event => event.feedback === null)).toBe(true);
  await page.unroute('**/api/product/feedback/*');
  await page.getByRole('button', { name: 'Обновить', exact: true }).click();
  await expect(button).toBeEnabled();
});

for (const width of [320, 768, 1440]) test(`навигация, лента и регистрация ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.route('https://tile.openstreetmap.org/**', route => route.abort());
  for (const path of ['/', '/register', '/profile', '/notifications']) {
    await page.goto(path);
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
    await expect(page.getByRole('navigation', { name: 'Основное меню' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: `.local/product-screens/${path.slice(1) || 'feed'}-${width}.png` });
  }
  await page.goto('/map');
  await expect(page.locator('.pm-marker').first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `.local/product-screens/map-offline-${width}.png`, fullPage: true });
  await page.locator('.pm-marker').first().click();
  const group = page.getByRole('dialog', { name: 'События в этой точке', exact: true });
  await expect(group).toBeVisible();
  await expect.poll(async () => group.evaluate(element => {
    const popup = element.getBoundingClientRect();
    const map = element.closest('.pm-canvas')!.getBoundingClientRect();
    return popup.left >= map.left - 1 && popup.right <= map.right + 1 && popup.top >= map.top - 1 && popup.bottom <= map.bottom + 1;
  })).toBe(true);
  await page.screenshot({ path: `.local/product-screens/map-popup-${width}.png`, fullPage: true });
  await group.locator('.pm-popup-event').last().click();
  await expect(group).toBeHidden();
  await expect(page.getByText(/Фон карты недоступен/)).toBeVisible();
  await page.goto('/');
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'К содержимому', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#product-main')).toBeFocused();
});

